/**
 * Write docs/ACCESS.md — who can do what in PODIUM — from the code itself.
 *
 *   npm run docs:access            the shipped roles (committed with the code)
 *   npm run docs:access -- --live  the roles as they are in the database named
 *                                  by DATABASE_URL, written to
 *                                  docs/ACCESS.live.local.md (not committed)
 *
 * The document is generated, never hand-edited: the permission catalog, the
 * shipped roles and the test-account table are the only sources, so it cannot
 * drift from what the code checks. The rules that are not a permission key —
 * the floor posts, the score console, the wave buttons — are written here
 * next to the file that enforces each one, so a change to one is a change to
 * the other in the same review.
 *
 * BFT MENA edits the live roles on the Roles screen, so the shipped roles are
 * starting points; --live shows what a running system actually grants.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { PERMISSION_TREE, PERMISSIONS, permissionEntry, type PermissionPolicy } from "../src/lib/permissions/catalog.ts";
import { DEFAULT_ROLE_FOR, SYSTEM_ROLES, type SystemRoleDef } from "../src/lib/permissions/system-roles.ts";
import { TEST_ACCOUNTS, testAccountEmail } from "../src/lib/permissions/test-account-roles.ts";

type RoleRow = Pick<SystemRoleDef, "key" | "name" | "description" | "assignableBy" | "accountTypes" | "permissions">;

const POLICY: Record<PermissionPolicy, string> = {
  general: "everyone",
  role: "role",
  bftOnly: "BFT MENA only",
  fullAdminOnly: "Full access only",
};

const ACCOUNT_TYPE: Record<string, string> = {
  admin: "BFT MENA · Full access",
  staff: "BFT MENA · Limited (Partial) access",
  studio: "Gym / Studio",
  organiser: "Organiser (event staff)",
  competitor: "Athlete",
};

async function liveRoles(): Promise<RoleRow[]> {
  const { PrismaMariaDb } = await import("@prisma/adapter-mariadb");
  const { PrismaClient } = await import("../src/generated/prisma/client.ts");
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("--live needs DATABASE_URL (node --env-file=… scripts/access-doc.ts --live)");
  const prisma = new PrismaClient({ adapter: new PrismaMariaDb(url) });
  try {
    const rows = await prisma.accessRole.findMany({ orderBy: [{ sortOrder: "asc" }, { name: "asc" }] });
    return rows.map((row) => ({
      key: row.key,
      name: row.name,
      description: row.description ?? "",
      assignableBy: row.assignableBy,
      accountTypes: (Array.isArray(row.accountTypes) ? row.accountTypes : []) as SystemRoleDef["accountTypes"],
      permissions: (Array.isArray(row.permissions) ? row.permissions : []).filter(
        (key): key is SystemRoleDef["permissions"][number] => typeof key === "string" && !!permissionEntry(key)
      ),
    }));
  } finally {
    await prisma.$disconnect();
  }
}

const live = process.argv.includes("--live");
const roles: RoleRow[] = live ? await liveRoles() : SYSTEM_ROLES;
const lines: string[] = [];
const out = (...text: string[]) => lines.push(...text);


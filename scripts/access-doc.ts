// ── The roles, one by one ────────────────────────────────────────────────────
const always = PERMISSIONS.filter((entry) => entry.policy === "general");
out(
  "## The roles",
  "",
  `Every signed-in account also has the always-on pages: ${always.map((entry) => `${entry.screenLabel}`).join(", ")}.`,
  ""
);
for (const role of roles) {
  out(`### ${role.name}`, "");
  if (role.description) out(role.description, "");
  out(
    `- **Given by:** ${role.assignableBy === "bft_studio" ? "BFT MENA and studios" : "BFT MENA only"}`,
    `- **Meant for:** ${role.accountTypes.length ? role.accountTypes.map((type) => ACCOUNT_TYPE[type] ?? type).join(", ") : "any account type"}`,
    ""
  );
  const held = new Set<string>(role.permissions);
  const screens = PERMISSION_TREE.flatMap((module) =>
    module.screens
      .map((screen) => ({
        module: module.label,
        screen: screen.label,
        actions: screen.permissions.filter((entry) => entry.policy !== "general" && held.has(entry.key)),
      }))
      .filter((screen) => screen.actions.length)
  );
  if (!screens.length) {
    out("_No permissions of its own — only the always-on pages._", "");
    continue;
  }
  out("| Area | Screen | Can |", "| --- | --- | --- |");
  for (const screen of screens) {
    const can = screen.actions
      .map((entry) => `${entry.label}${entry.policy === "bftOnly" ? " _(BFT MENA accounts only)_" : ""}`)
      .join("; ");
    out(`| ${screen.module} | ${screen.screen} | ${can} |`);
  }
  out("");
}

